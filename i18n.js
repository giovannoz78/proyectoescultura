let locale = "es";
const tr = (value) => locale === "en" ? translations[value] ?? value : value;
function initLanguage() {
  const nodes = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement.closest("script, .solar-en, #portrait-grid, #light-caption") && translations[node.data.trim()]) nodes.push([node,node.data]);
  }
  const attrs = [];
  document.querySelectorAll("[aria-label], [alt]").forEach(element => {
    if (element.closest("#portrait-grid, #zoom figure") || element.id === "light-img") return;
    for (const name of ["aria-label","alt"]) {
      const value = element.getAttribute(name);
      if (translations[value]) attrs.push([element,name,value]);
    }
  });
  const buttons = [...document.querySelectorAll("[data-lang]")];
  function select(language) {
    locale = language === "en" ? "en" : "es";
    document.documentElement.lang = locale;
    document.title = "Hier ist kein Warum · " + tr("Aquí no hay por qué");
    document.querySelector('meta[name=description]').content = locale === "en"
      ? "Interactive dossier for Hier ist kein Warum, a memorial sculpture proposal by Amplitud Foundation."
      : "Dossier interactivo de Hier ist kein Warum, propuesta de escultura memorial de Amplitud Foundation.";
    for (const [node,original] of nodes) node.data = original.replace(original.trim(),tr(original.trim()));
    for (const [element,name,value] of attrs) element.setAttribute(name,tr(value));
    for (const button of buttons) button.setAttribute("aria-pressed",String(button.dataset.lang===locale));
    document.querySelector("[data-light][aria-pressed=true]").click();
    document.querySelector("[data-series][aria-pressed=true]").click();
    try { localStorage.setItem("hiwk-language",locale); } catch {}
  }
  buttons.forEach(button=>button.addEventListener("click",()=>select(button.dataset.lang)));
  let saved;
  try { saved=localStorage.getItem("hiwk-language"); } catch {}
  const query=new URLSearchParams(location.search).get("lang");
  select(["es","en"].includes(query) ? query : saved || "es");
}
